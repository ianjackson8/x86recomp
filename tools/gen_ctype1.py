#!/usr/bin/env python3
"""Windows CT_CTYPE1 classes for U+0100..U+FFFF from Unicode general
categories (Python's unicodedata), as ranges for src/runtime/hle/win32_ctype1.inc.

Usage: python3 -I tools/gen_ctype1.py > src/runtime/hle/win32_ctype1.inc

Mapping (GetStringTypeW's classes): Lu upper+alpha, Ll lower+alpha, Lt/Lm/Lo
alpha, Nd digit, Zs space+blank, Zl/Zp space, Cc/Cf control, P*/S*/Nl/No
punctuation; marks, surrogates, private use and unassigned: none.
"""
import sys
import unicodedata

UPPER, LOWER, DIGIT, SPACE, PUNCT, CNTRL, BLANK, ALPHA = 1, 2, 4, 8, 0x10, 0x20, 0x40, 0x100


def bits(cp):
    cat = unicodedata.category(chr(cp))
    if cat == 'Lu': return UPPER | ALPHA
    if cat == 'Ll': return LOWER | ALPHA
    if cat in ('Lt', 'Lm', 'Lo'): return ALPHA
    if cat == 'Nd': return DIGIT
    if cat == 'Zs': return SPACE | BLANK
    if cat in ('Zl', 'Zp'): return SPACE
    if cat in ('Cc', 'Cf'): return CNTRL
    if cat[0] in 'PS' or cat in ('Nl', 'No'): return PUNCT
    return 0


ranges = []
for cp in range(0x100, 0x10000):
    b = bits(cp)
    if ranges and ranges[-1][2] == b and ranges[-1][1] == cp - 1:
        ranges[-1][1] = cp
    else:
        ranges.append([cp, cp, b])
out = sys.stdout
out.write('// Generated by tools/gen_ctype1.py (Unicode %s): CT_CTYPE1 classes of\n'
          '// U+0100..U+FFFF as {first, last, classes} ranges. Do not edit.\n'
          % unicodedata.unidata_version)
for f, l, b in ranges:
    if b:
        out.write('{0x%04X, 0x%04X, 0x%03X},\n' % (f, l, b))
