#!/usr/bin/env python3
"""Steam interface vtables, in MSVC order, from a Steamworks SDK's headers.

Usage: python3 -I tools/steam_vtables.py SDK/public/steam OUT.inc

A 32-bit Windows guest calls a Steam interface through an MSVC vtable. MSVC
lays out a class's virtual functions in declaration order, except that a
set of overloads (same name) is placed together at the position of the
first one, in reverse declaration order. The SDK headers give the
declaration order of the version the game was built with (pick the SDK
whose *_INTERFACE_VERSION strings match the game's).

OUT.inc gets, per interface, a line
  RECOMP_STEAM_IFACE(ClassName, "VersionString", "m1", "m2", ...)
with each overloaded method named Name(params) so each has its own handler;
the others are named Name. Nothing from the SDK is written elsewhere.
"""
import os
import re
import sys

CLASSES = {  # header, class, version macro
    'isteamclient.h': ('ISteamClient', 'STEAMCLIENT_INTERFACE_VERSION'),
    'isteamuser.h': ('ISteamUser', 'STEAMUSER_INTERFACE_VERSION'),
    'isteamfriends.h': ('ISteamFriends', 'STEAMFRIENDS_INTERFACE_VERSION'),
    'isteamutils.h': ('ISteamUtils', 'STEAMUTILS_INTERFACE_VERSION'),
    'isteamapps.h': ('ISteamApps', 'STEAMAPPS_INTERFACE_VERSION'),
    'isteamuserstats.h': ('ISteamUserStats', 'STEAMUSERSTATS_INTERFACE_VERSION'),
}


def methods(text, cls):
    """(name, params) of cls's virtual functions, in declaration order."""
    m = re.search(r'^class\s+%s\s*$\s*\{(.*?)^\};' % cls, text, re.S | re.M)
    if not m:
        sys.exit('steam_vtables: no class %s' % cls)
    body = re.sub(r'//[^\n]*', '', m.group(1))
    body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
    out = []
    for v in re.finditer(r'\bvirtual\b(.*?);', body, re.S):
        decl = ' '.join(v.group(1).split())
        f = re.search(r'([A-Za-z_][A-Za-z_0-9]*)\s*\((.*)\)\s*(const)?\s*(=\s*0)?\s*$', decl)
        if not f:
            sys.exit('steam_vtables: cannot parse "virtual %s" in %s' % (decl, cls))
        params = re.sub(r'STEAM_[A-Z_]+\([^()]*\)', '', f.group(2))  # annotation macros
        out.append((f.group(1), ' '.join(params.split())))
    return out


def msvc_order(ms):
    names = [n for n, _ in ms]
    order, seen = [], set()
    for n, _ in ms:
        if n in seen:
            continue
        seen.add(n)
        group = [m for m in ms if m[0] == n]
        order.extend(reversed(group))
    return order, {n for n in names if names.count(n) > 1}


def main():
    inc, out = sys.argv[1], sys.argv[2]
    lines = ['// Generated by tools/steam_vtables.py from the Steamworks SDK headers in',
             '// the build configuration; not part of the source tree.']
    for header, (cls, macro) in CLASSES.items():
        text = open(os.path.join(inc, header), encoding='latin-1').read().replace('\r', '')
        ver = re.search(r'#define\s+%s\s+"([^"]+)"' % macro, text)
        if not ver:
            sys.exit('steam_vtables: no %s in %s' % (macro, header))
        order, over = msvc_order(methods(text, cls))
        names = ['"%s"' % (n + '(' + p + ')' if n in over else n) for n, p in order]
        lines.append('RECOMP_STEAM_IFACE(%s, "%s", %s)' % (cls, ver.group(1), ', '.join(names)))
    with open(out, 'w') as f:
        f.write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
